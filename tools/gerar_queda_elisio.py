def grade_para_img(grade: str) -> Image.Image:
    linhas = [l for l in grade.strip("\n").split("\n")]
    assert len(linhas) == 16, len(linhas)
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, linha in enumerate(linhas):
        assert len(linha) == 16, (y, linha)
        for x, c in enumerate(linha):
            if c != ".":
                img.putpixel((x, y), PALETA[c])
    return img


def frame_eli(sheet: Image.Image, i: int) -> Image.Image:
    return sheet.crop((i * 16, 0, i * 16 + 16, 16)).transpose(Image.FLIP_LEFT_RIGHT)


def gerar() -> Image.Image:
    eli = Image.open(ELI).convert("RGBA")
    frames = [frame_eli(eli, i) for i in (4, 5, 6, 7, 13, 14, 15)]
    frames += [grade_para_img(g) for g in (SALTO_ALCANCE, PERDA, QUEDA, IMPACTO)]
    frames.append(grade_para_img(DEITADO))
    sheet = Image.new("RGBA", (16 * len(frames), 16), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        sheet.paste(f, (i * 16, 0))
    return sheet


def preview(sheet: Image.Image, caminho: str, indices=(4, 7, 8, 9, 10, 11), escala=8) -> None:
    fundo = (22, 26, 44, 255)
    gap = 2
    w = len(indices) * (16 + gap) + gap
    img = Image.new("RGBA", (w, 16 + gap * 2), fundo)
    for n, i in enumerate(indices):
        img.alpha_composite(sheet.crop((i * 16, 0, i * 16 + 16, 16)), (gap + n * (16 + gap), gap))
    img.resize((img.width * escala, img.height * escala), Image.NEAREST).save(caminho)


if __name__ == "__main__":
    sheet = gerar()
    sheet.save(SAIDA)
    print("salvo", SAIDA, sheet.size)
    if "--preview" in sys.argv:
        caminho = sys.argv[sys.argv.index("--preview") + 1]
        preview(sheet, caminho)
        print("preview", caminho)
